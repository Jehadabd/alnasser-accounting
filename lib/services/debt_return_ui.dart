// 👑 «تسديد دين راجع» ميزة حساب المالك (مرتبطة بنقاط المؤسسين):
//   • إنشاؤها من «إضافة معاملة» يظهر للمالك فقط.
//   • في التقارير: المالك يرى البطاقة دائماً باسمها. غيره يراها فقط إن كان في الفترة
//     مبلغ، باسم «مرتجعات على الحساب» — لأن المجموع نفسه يشمل «مرتجع المبيعات على
//     الحساب» (ميزة عامة) ومعاملات قديمة سُجّلت قبل التقييد. إخفاؤها حينها يُخفي
//     حركة غيّرت أرصدة العملاء فلا تتطابق التقارير مع الأرصدة.

import '../owner/owner_access.dart';

class DebtReturnUi {
  DebtReturnUi._();

  static bool get owner => OwnerAccess.enabled;

  static String get label => owner ? 'تسديد دين راجع' : 'مرتجعات على الحساب';

  /// تظهر البطاقة؟ للمالك دائماً، ولغيره إن وُجد مبلغ فقط.
  static bool show(double amount) => owner || amount.abs() >= 1;
}
